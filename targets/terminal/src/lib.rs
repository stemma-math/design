//! Stemma's design system for terminals.
//!
//! A set of themes, not a framework:
//!
//! - [`Role`]s, not colours: the intents (accent, success, warning,
//!   danger, info) and text roles (muted, identifier, strong). Each maps to
//!   one of the 16 named ANSI colours, so it follows the terminal's own
//!   theme; [`Role::rgb`] gives the design tokens' value for the occasional
//!   truecolour accent.
//! - The shared [`Symbol`]s and spinner frames, each with an ASCII
//!   alternative.
//! - One colour policy, [`Output`]: `NO_COLOR`, output that is not a
//!   terminal, `TERM=dumb` and an explicit plain switch (for `--json` and
//!   the like) are decided in one place.
//! - Themes for the libraries a tool already uses, behind features: `clap`
//!   ([`themes::clap::styles`]), `cliclack` ([`themes::cliclack::Theme`]) and
//!   `indicatif` ([`themes::indicatif`]). A tool keeps calling its library
//!   directly and only takes the theme.
//!
//! ```
//! use stemma_design_terminal::{Output, Role, Stream, Symbol};
//!
//! let out = Output::detect(Stream::Stdout);
//! println!("{} {}", out.paint(Role::Success, out.symbol(Symbol::Success)), "Signed in");
//! ```

