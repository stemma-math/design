/// One of the 16 named ANSI colours.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Ansi {
    Black,
    Red,
    Green,
    Yellow,
    Blue,
    Magenta,
    Cyan,
    White,
    BrightBlack,
    BrightRed,
    BrightGreen,
    BrightYellow,
    BrightBlue,
    BrightMagenta,
    BrightCyan,
    BrightWhite,
}

impl Ansi {
    /// The SGR parameter that sets it as the foreground.
    pub fn foreground(self) -> u8 {
        match self {
            Ansi::Black => 30,
            Ansi::Red => 31,
            Ansi::Green => 32,
            Ansi::Yellow => 33,
            Ansi::Blue => 34,
            Ansi::Magenta => 35,
            Ansi::Cyan => 36,
            Ansi::White => 37,
            Ansi::BrightBlack => 90,
            Ansi::BrightRed => 91,
            Ansi::BrightGreen => 92,
            Ansi::BrightYellow => 93,
            Ansi::BrightBlue => 94,
            Ansi::BrightMagenta => 95,
            Ansi::BrightCyan => 96,
            Ansi::BrightWhite => 97,
        }
    }
}

/// What a piece of text is, which decides how it looks.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Role {
    /// The thing to look at: a heading, the current step, a prompt.
    Accent,
    /// Something done or in good order.
    Success,
    /// Something to keep in mind before going on.
    Warning,
    /// An error, or something destructive.
    Danger,
    /// Something worth knowing, with no action needed.
    Info,
    /// Secondary text: hints, counts, what is already done.
    Muted,
    /// Verbatim words: names, paths, versions, commands.
    Identifier,
    /// Emphasis, in the terminal's own colour.
    Strong,
}

impl Role {
    /// Every role.
    pub const ALL: [Role; 8] = [
        Role::Accent,
        Role::Success,
        Role::Warning,
        Role::Danger,
        Role::Info,
        Role::Muted,
        Role::Identifier,
        Role::Strong,
    ];

    /// The ANSI colour it takes; none for `Strong`.
    pub fn ansi(self) -> Option<Ansi> {
        match self {
            Role::Accent => Some(Ansi::Blue),
            Role::Success => Some(Ansi::Green),
            Role::Warning => Some(Ansi::Yellow),
            Role::Danger => Some(Ansi::Red),
            Role::Info => Some(Ansi::Cyan),
            Role::Muted => Some(Ansi::BrightBlack),
            Role::Identifier => Some(Ansi::Magenta),
            Role::Strong => None,
        }
    }

    /// Whether it is set in bold.
    pub fn bold(self) -> bool {
        matches!(self, Role::Accent | Role::Danger | Role::Strong)
    }

    /// The design tokens' colour for it in `palette`; none for `Strong`.
    pub fn rgb(self, palette: &Palette) -> Option<Rgb> {
        match self {
            Role::Accent => Some(palette.accent),
            Role::Success => Some(palette.success),
            Role::Warning => Some(palette.warning),
            Role::Danger => Some(palette.danger),
            Role::Info => Some(palette.info),
            Role::Muted => Some(palette.muted),
            Role::Identifier => Some(palette.identifier),
            Role::Strong => None,
        }
    }

    /// The SGR parameters that set it, as `1;34`.
    pub fn sgr(self) -> String {
        let mut codes = Vec::new();
        if self.bold() {
            codes.push("1".to_owned());
        }
        if let Some(ansi) = self.ansi() {
            codes.push(ansi.foreground().to_string());
        }
        codes.join(";")
    }
}

/// A symbol every Stemma tool uses the same way.
