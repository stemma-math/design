//! Stemma's design system for Rust.
//!
//! The files of the web target (`@stemma-math/design`) as constants, under
//! paths that do not depend on how this repository is laid out:
//!
//! - `web/…`: the stylesheets, the faces, the glyph sprite and the grain;
//! - `elements/…`: the custom elements, with the `elements` feature;
//! - `brand-kit/…`: favicons, application icons and the marks as SVG, with
//!   the `brand-kit` feature.
//!
//! A server serves them under a prefix of its choice with [`get`] or
//! [`serve`]; the files refer to each other by relative paths, so the
//! layout below the prefix is all they need. A page kept in a single HTML
//! file inlines what it needs with [`bundle::Bundle`].
//!
//! ```
//! let asset = stemma_design::get("web/index.css").unwrap();
//! assert_eq!(asset.content_type, "text/css; charset=utf-8");
//! ```

// Generated by tools/targets.py.
#[rustfmt::skip]
mod assets;
pub mod bundle;
#[rustfmt::skip]
mod bundle_data;

/// One file, with the media type to serve it as.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Asset {
    /// The path, relative to wherever the files are served from, as
    /// `web/tokens.css`.
    pub path: &'static str,
    /// The media type, as for a `Content-Type` header.
    pub content_type: &'static str,
    /// The file's contents.
    pub bytes: &'static [u8],
}

impl Asset {
    /// The contents as text, for the files that are text.
    pub fn text(&self) -> Option<&'static str> {
        std::str::from_utf8(self.bytes).ok()
    }
}

/// Every file this build carries, by group: the web target's, then the
/// elements' and the brand kit's where their features are on.
pub fn assets() -> impl Iterator<Item = &'static Asset> {
    #[allow(unused_mut)]
    let mut groups: Vec<&'static [Asset]> = vec![assets::WEB];
    #[cfg(feature = "elements")]
    groups.push(assets::ELEMENTS);
    #[cfg(feature = "brand-kit")]
    groups.push(assets::BRAND_KIT);
    groups.into_iter().flatten()
}

/// The file at `path`, as `web/fonts.css`; a leading `/` is ignored.
pub fn get(path: &str) -> Option<&'static Asset> {
    let path = path.trim_start_matches('/');
    assets().find(|asset| asset.path == path)
}

/// The file a request for `request_path` asks for, when the files are
/// served under `prefix`, as `/design`. `None` when the request is outside
/// the prefix or names no file.
///
/// ```
/// let asset = stemma_design::serve("/design", "/design/web/tokens.css").unwrap();
/// assert_eq!(asset.path, "web/tokens.css");
/// assert!(stemma_design::serve("/design", "/other/web/tokens.css").is_none());
/// ```
pub fn serve(prefix: &str, request_path: &str) -> Option<&'static Asset> {
    let prefix = prefix.trim_end_matches('/');
    let rest = request_path.strip_prefix(prefix)?;
    rest.strip_prefix('/').and_then(get)
}

/// Where a glyph is when the files are served under `prefix`, for
/// `<use href>`: in the web target's sprite. A page that inlines a bundle
/// takes [`bundle::Bundle::glyph_href`] instead.
///
/// ```
/// assert_eq!(stemma_design::glyph_href("/design", "info"), "/design/web/glyphs.svg#info");
/// ```
pub fn glyph_href(prefix: &str, name: &str) -> String {
    format!("{}/web/glyphs.svg#{name}", prefix.trim_end_matches('/'))
}
